"""Print (or update in README.md) the settings reference, generated from config.Settings.

    python scripts/gen_settings_docs.py            # print Markdown
    python scripts/gen_settings_docs.py --write    # replace the block between the markers in README.md
    python scripts/gen_settings_docs.py --check    # exit 1 if README.md is out of date

Needs the backend installed (pip install -e backend).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from ai_server_monitor.config import settings_json_schema  # noqa: E402
from ai_server_monitor.main import SECTION_TITLES  # noqa: E402

START = "<!-- settings-reference:start (generated by scripts/gen_settings_docs.py) -->"
END = "<!-- settings-reference:end -->"


def resolve(node: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any]:
    if "$ref" in node:
        extra = {k: v for k, v in node.items() if k != "$ref"}
        return {**resolve(defs[node["$ref"].split("/")[-1]], defs), **extra}
    return node


def kind(node: dict[str, Any], defs: dict[str, Any]) -> str:
    node = resolve(node, defs)
    if "anyOf" in node:
        options = [resolve(o, defs) for o in node["anyOf"]]
        consts = [o["const"] for o in options if "const" in o]
        if any(o.get("type") == "boolean" for o in options) and consts:
            return "on / off / " + " / ".join(map(str, consts))
        return " or ".join(kind(o, defs) for o in options if o.get("type") != "null")
    if node.get("format") == "duration":
        return "duration"
    if node.get("format") == "password":
        return "secret"
    if "enum" in node:
        return " / ".join(map(str, node["enum"]))
    if "const" in node:
        return str(node["const"])
    if node.get("type") == "array":
        return f"list of {kind(node.get('items', {}), defs)}"
    if node.get("type") == "object":
        return "map" if node.get("additionalProperties") is not None else "object"
    return str(node.get("type", "text"))


def show_default(node: dict[str, Any], required: bool = False) -> str:
    if "default" not in node:
        return "required" if required else "empty"
    value = node["default"]
    if value in ("", [], {}, None):
        return "empty"
    if isinstance(value, bool):
        return "on" if value else "off"
    return f"`{value}`"


def constraints(node: dict[str, Any]) -> str:
    bits = []
    if "minimum" in node:
        bits.append(f"min {node['minimum']}")
    if "maximum" in node:
        bits.append(f"max {node['maximum']}")
    return f" ({', '.join(bits)})" if bits else ""


def clean(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    # Table cell: escape what Markdown would take for a pipe, emphasis or an HTML tag.
    return text.replace("|", "\\|").replace("*", "\\*").replace("<", "&lt;")


def rows(
    node: dict[str, Any],
    path: str,
    defs: dict[str, Any],
    out: list[list[str]],
    defaults: dict[str, Any] | None = None,
) -> None:
    """Add one row per setting. `defaults` are the values of the enclosing group's own
    default instance: they win over the field defaults of the class (a group such as
    `cutoff_search` is created with other values than its class defaults)."""
    node = resolve(node, defs)
    defaults = defaults or {}
    required = set(node.get("required") or [])
    for key, prop in (node.get("properties") or {}).items():
        full = f"{path}.{key}" if path else key
        p = resolve(prop, defs)
        if key in defaults:
            p = {**p, "default": defaults[key]}
        group_defaults = p.get("default") if isinstance(p.get("default"), dict) else {}
        nested = p
        if "anyOf" in p:  # optional group, e.g. `proxy: ProxySettings | None`
            objects = [resolve(o, defs) for o in p["anyOf"] if o.get("type") != "null"]
            if len(objects) == 1 and objects[0].get("properties"):
                nested = {
                    **objects[0],
                    "description": p.get("description") or objects[0].get("description"),
                }
        items = resolve(p["items"], defs) if p.get("type") == "array" and "items" in p else None
        if nested.get("properties"):
            if nested.get("description"):
                out.append([f"**{full}**", "group", "", clean(nested["description"])])
            rows(nested, full, defs, out, group_defaults)
        elif items is not None and items.get("properties"):
            out.append(
                [f"**{full}**", "list of groups", "empty", clean(p.get("description") or "")]
            )
            rows(items, f"{full}[]", defs, out)
        else:
            out.append(
                [
                    f"`{full}`",
                    kind(prop, defs) + constraints(p),
                    show_default(p, key in required),
                    clean(p.get("description") or "") or "—",
                ]
            )


def reference() -> str:
    schema = settings_json_schema()
    defs = schema.get("$defs", {})
    parts: list[str] = []
    for key, prop in schema["properties"].items():
        table: list[list[str]] = []
        rows(prop, key, defs, table)
        parts.append(f"### {SECTION_TITLES.get(key, key.title())} (`{key}`)\n")
        parts.append("| Setting | Type | Default | What it does |")
        parts.append("|---|---|---|---|")
        parts.extend("| " + " | ".join(r) + " |" for r in table)
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    mode = sys.argv[1] if len(sys.argv) > 1 else ""
    text = reference()
    if mode not in ("--write", "--check"):
        sys.stdout.write(text)
        return 0
    readme = ROOT / "README.md"
    current = readme.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(current):
        sys.stderr.write("README.md has no settings-reference markers\n")
        return 2
    updated = pattern.sub(lambda _: f"{START}\n\n{text}\n{END}", current)
    if mode == "--check":
        if updated != current:
            sys.stderr.write("README.md settings reference is out of date: run --write\n")
            return 1
        return 0
    readme.write_text(updated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
